// Generates src/tables.ts from ../format/tables.json (the frozen, normative tables).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "..", "..", "format", "tables.json"), "utf8"));
const A = t.alphabet;
const enc = (v, chars) => {
  let s = "";
  for (let k = chars - 1; k >= 0; k--) s += A[Math.floor(v / 64 ** k) % 64];
  return s;
};
const coefs = (p) => p.coefs.map(([c, u, v]) => enc((c << 8) | (u << 4) | v, 2)).join("");
const seq = (p) => p.seq.map((i) => enc(i, 2)).join("");
if (JSON.stringify(t.scales) !== "[2,3,4,6]") throw new Error("scales changed: update src/core.ts");
if (t.g.length !== 2 || t.g[0].length !== 8 || t.g[1].length !== 8) throw new Error("expected g = [luma[8], chroma[8]]");
const out = `// GENERATED by scripts/gen-tables.mjs from format/tables.json - do not edit.
// DCTHash v${t.version} frozen tables.  Packed with the hash alphabet, big-endian 6-bit digits.
/** hash alphabet (base64url) */
export const A = ${JSON.stringify(A)};
/** photo profile coefficients: 2 digits each = channel << 8 | u << 4 | v */
export const PC = ${JSON.stringify(coefs(t.photo))};
/** photo profile means M: 3 digits each, offset 131072 */
export const PM = ${JSON.stringify(t.photo.M.map((m) => enc(m + 131072, 3)).join(""))};
/** photo profile scales S: 3 digits each */
export const PS = ${JSON.stringify(t.photo.S.map((s) => enc(s, 3)).join(""))};
/** photo profile bit sequence: 2 digits each = index of the coefficient that receives the k-th payload bit */
export const PQ = ${JSON.stringify(seq(t.photo))};
/** smooth profile coefficients and bit sequence */
export const SC = ${JSON.stringify(coefs(t.smooth))};
export const SQ = ${JSON.stringify(seq(t.smooth))};
/** loading factors x256 for bit depths 1..8 (photo profile, non-DC coefficients): [luma, chroma] */
export const G = ${JSON.stringify(t.g)};
/** aspect ratios width:height for codes 0..30, flattened */
export const R = ${JSON.stringify(t.aspects.flat())};
`;
writeFileSync(join(here, "..", "src", "tables.ts"), out);
console.log(`tables.ts: photo ${t.photo.coefs.length} coefficients, smooth ${t.smooth.coefs.length}, ${out.length} chars`);
